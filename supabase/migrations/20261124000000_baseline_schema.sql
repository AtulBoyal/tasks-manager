-- Baseline: the production schema as of 2026-11-24, captured from the live
-- database. Use it to create a fresh database. It has already been applied
-- to production; do not run it there again (see supabase/README.md).

-- ---------------------------------------------------------------------------
-- profiles: one row per user, app settings
-- ---------------------------------------------------------------------------
create table public.profiles (
  id              uuid not null,
  codeforces_sync boolean default false,
  created_at      timestamptz default now(),

  constraint profiles_pkey primary key (id),
  constraint profiles_id_fkey foreign key (id)
    references auth.users (id) on delete cascade
);

-- ---------------------------------------------------------------------------
-- tasks
-- ---------------------------------------------------------------------------
create table public.tasks (
  id              bigint generated by default as identity,
  name            text not null,
  factor          text,
  last_date       text,
  completed       boolean default false,
  completion_date text,
  links           jsonb default '[]'::jsonb,
  tags            jsonb default '[]'::jsonb,
  subtasks        jsonb default '[]'::jsonb,
  recurrence      text default 'none'::text,
  start_date      date,
  user_id         uuid default auth.uid(),
  archived        boolean default false,
  cf_contest_id   bigint,

  constraint tasks_pkey primary key (id),
  constraint tasks_user_id_fkey foreign key (user_id)
    references auth.users (id)
);

-- One task per Codeforces contest per user (two identical indexes exist in
-- production; the duplicate is removed in the next migration)
create unique index unique_cf_task
  on public.tasks using btree (user_id, cf_contest_id)
  where (cf_contest_id is not null);

create unique index tasks_user_contest_uniq
  on public.tasks using btree (user_id, cf_contest_id)
  where (cf_contest_id is not null);

-- ---------------------------------------------------------------------------
-- Row Level Security: users can only see and change their own rows
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.tasks enable row level security;

create policy "Users can read own profile" on public.profiles
  for select using (auth.uid() = id);

create policy "Users can insert own profile" on public.profiles
  for insert with check (auth.uid() = id);

create policy "Users can update own profile" on public.profiles
  for update using (auth.uid() = id);

create policy "Users can view own tasks" on public.tasks
  for select using (auth.uid() = user_id);

create policy "Users can insert own tasks" on public.tasks
  for insert with check (auth.uid() = user_id);

create policy "Users can update own tasks" on public.tasks
  for update using (auth.uid() = user_id);

create policy "Users can delete own tasks" on public.tasks
  for delete using (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- Realtime: the app subscribes to changes on tasks
-- ---------------------------------------------------------------------------
alter publication supabase_realtime add table public.tasks;
